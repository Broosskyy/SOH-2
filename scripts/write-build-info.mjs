import { execSync } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const outDir = resolve(root, "app/generated");
const outFile = resolve(outDir, "buildInfo.ts");

const release = process.env.BUILD_RELEASE ?? "V20.3";
let commit = "unknown";
try {
  commit = execSync("git rev-parse --short HEAD", {
    cwd: root,
    encoding: "utf8",
  }).trim();
} catch {
  commit = process.env.BUILD_COMMIT ?? "unknown";
}

const builtAt = new Date().toISOString();

await mkdir(outDir, { recursive: true });
await writeFile(
  outFile,
  `// Generated by scripts/write-build-info.mjs — do not edit manually.
export const BUILD_RELEASE = ${JSON.stringify(release)} as const;
export const BUILD_COMMIT = ${JSON.stringify(commit)} as const;
export const BUILD_BUILT_AT = ${JSON.stringify(builtAt)} as const;
`,
  "utf8",
);

console.log(`[build-info] ${release} @ ${commit} → app/generated/buildInfo.ts`);
